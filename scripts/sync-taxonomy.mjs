// Rebuild src/dsl/taxonomy.json: the IDs a lesson's `skill_paths` may name.
//
//   node scripts/sync-taxonomy.mjs
//
// An ID is valid when one of its owners defines it:
//
//   - bridge-common-conventions defines conventions, natural methods, skills
//     and judgement entries (its published snapshot, pack.json);
//   - a lesson collection defines its own lesson sets, as the skill paths in
//     its manifest (Baker-Bridge: "Stayman & Transfers (Partnership)" is a
//     set of lessons, which the conventions list does not hold).
//
// The file is a bundled copy, so validation needs no network. Run this when
// a lesson needs an ID that one of those sources has added; the copy records
// which version of each it was taken from.
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const PACK = 'https://bridge-craftwork.github.io/bridge-common-conventions/'
const COLLECTIONS = [
  { name: 'Baker-Bridge', manifest: 'https://raw.githubusercontent.com/bridge-craftwork/Baker-Bridge/main/bridge-classroom/manifest.json' },
]

const get = async (url) => {
  const resp = await fetch(url)
  if (!resp.ok) throw new Error(`${url}: ${resp.status}`)
  return resp.json()
}

const [manifest, pack] = await Promise.all([get(`${PACK}manifest.json`), get(`${PACK}pack.json`)])
const defined = new Set([...Object.keys(pack.conventions || {}), ...Object.keys(pack.skills || {})])
const sources = [{ name: 'bridge-common-conventions', rules_number: manifest.rules_number, commit: manifest.source_commit, ids: defined.size }]

const paths = new Set(defined)
for (const c of COLLECTIONS) {
  const m = await get(c.manifest)
  const own = new Set()
  for (const lesson of Object.values(m.lessons || {})) {
    for (const p of [lesson.skillPath, ...(lesson.boards || []).map((b) => b.skillPath)]) {
      if (p && !defined.has(p)) own.add(p)
    }
  }
  for (const p of own) paths.add(p)
  sources.push({ name: c.name, commit: m.generatedAtCommit, lesson_sets: own.size })
}

const out = {
  schema: 'taxonomy/v1',
  note: 'Generated by scripts/sync-taxonomy.mjs: do not edit. Conventions, natural methods and skills are bridge-common-conventions\'; lesson sets are their collection\'s.',
  sources,
  paths: [...paths].sort(),
}
const target = fileURLToPath(new URL('../src/dsl/taxonomy.json', import.meta.url))
writeFileSync(target, JSON.stringify(out, null, 2) + '\n')
console.log(`src/dsl/taxonomy.json: ${out.paths.length} IDs (${sources.map((s) => `${s.name}: ${s.ids ?? s.lesson_sets}`).join(', ')})`)
